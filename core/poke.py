"""Social poke (戳一戳) replies: variety, streak, optional poke-back.

Poke is a tap, not an attachment. This policy selects silence, an LLM reply,
or a poke-back; reply wording is generated by the configured reply provider.
"""

from __future__ import annotations

import random
from collections import deque
from collections.abc import Iterable
from dataclasses import dataclass
from typing import Any, Optional

from .vibe_analyzer import GroupChatMode


_STREAK_WINDOW = 90.0


@dataclass(frozen=True)
class PokeContext:
    """Immutable social-signal snapshot for a poke turn."""

    poke_only: bool = True
    poke_at_bot: bool = False
    burst_count: int = 1
    sender_streak: int = 1
    ping_pong_turns: int = 0
    group_poke_count: int = 1
    distinct_pokers: int = 1
    poke_action_text: str = ""
    poke_target_identity: dict[str, Any] | None = None
    recent_bot_poked_sender: bool = False
    peer_poke_trigger_reason: str = ""

    def payload(self) -> dict[str, Any]:
        data: dict[str, Any] = {
            "poke_at_bot": bool(self.poke_at_bot),
            "burst_count": max(1, int(self.burst_count or 1)),
            "sender_streak": max(1, int(self.sender_streak or 1)),
            "ping_pong_turns": max(0, int(self.ping_pong_turns or 0)),
            "group_poke_count": max(1, int(self.group_poke_count or 1)),
            "distinct_pokers": max(0, int(self.distinct_pokers or 0)),
            "recent_bot_poked_sender": bool(self.recent_bot_poked_sender),
        }
        if self.poke_action_text:
            data["poke_action_text"] = str(self.poke_action_text)
        if self.poke_target_identity is not None:
            data["poke_target_identity"] = dict(self.poke_target_identity)
        if self.peer_poke_trigger_reason:
            data["peer_poke_trigger_reason"] = str(self.peer_poke_trigger_reason)
        return data


@dataclass(frozen=True)
class _PokeRecord:
    sender_id: str
    target_id: str
    is_bot_sender: bool
    is_bot_target: bool
    timestamp: float
    action_text: str = ""


class PokeTracker:
    """Pure 90s sliding-window signal tracker for group poke activity.

    Tracks burst, streak, ping-pong alternation, group pile-on, and recent
    bot pokes without applying any hard anti-spam or anti-loop suppression.
    """

    def __init__(
        self,
        *,
        window_seconds: float = _STREAK_WINDOW,
        max_events_per_session: int = 200,
        max_sessions: int = 2000,
    ) -> None:
        self._window_seconds = max(1.0, float(window_seconds))
        self._max_events_per_session = max(16, int(max_events_per_session))
        self._max_sessions = max(64, int(max_sessions))
        self._sessions: dict[str, deque[_PokeRecord]] = {}

    def _prune_session(self, session_id: str, now: float) -> deque[_PokeRecord]:
        sid = str(session_id or "")
        events = self._sessions.get(sid)
        if events is None:
            return deque()
        cutoff = float(now) - self._window_seconds
        while events and events[0].timestamp < cutoff:
            events.popleft()
        if not events:
            self._sessions.pop(sid, None)
            return deque()
        return events

    def _active_events(self, session_id: str, now: float) -> list[_PokeRecord]:
        events = self._prune_session(session_id, now)
        cutoff = float(now) - self._window_seconds
        ts = float(now)
        return [rec for rec in events if cutoff <= rec.timestamp <= ts + 1e-6]

    def _evict_if_needed(self, now: float) -> None:
        if len(self._sessions) <= self._max_sessions:
            return
        cutoff = float(now) - self._window_seconds
        stale = [
            sid
            for sid, events in self._sessions.items()
            if not events or events[-1].timestamp < cutoff
        ]
        for sid in stale:
            self._sessions.pop(sid, None)
        while len(self._sessions) > self._max_sessions:
            oldest_sid = min(
                self._sessions,
                key=lambda sid: self._sessions[sid][-1].timestamp if self._sessions[sid] else -1.0,
            )
            self._sessions.pop(oldest_sid, None)

    def record_poke(
        self,
        session_id: str,
        *,
        sender_id: str,
        target_id: str,
        is_bot_sender: bool = False,
        is_bot_target: bool = False,
        now: float,
        action_text: str = "",
    ) -> None:
        sid = str(session_id or "")
        ts = float(now)
        events = self._sessions.get(sid)
        if events is None:
            events = deque(maxlen=self._max_events_per_session)
            self._sessions[sid] = events
        else:
            cutoff = ts - self._window_seconds
            while events and events[0].timestamp < cutoff:
                events.popleft()
        events.append(
            _PokeRecord(
                sender_id=str(sender_id or ""),
                target_id=str(target_id or ""),
                is_bot_sender=bool(is_bot_sender),
                is_bot_target=bool(is_bot_target),
                timestamp=ts,
                action_text=str(action_text or ""),
            )
        )
        self._evict_if_needed(ts)

    def record_bot_poke(
        self,
        session_id: str,
        *,
        bot_id: str,
        target_id: str,
        now: float,
    ) -> None:
        self.record_poke(
            session_id,
            sender_id=str(bot_id or ""),
            target_id=str(target_id or ""),
            is_bot_sender=True,
            is_bot_target=False,
            now=now,
        )

    def peer_trigger_reason(
        self,
        session_id: str,
        *,
        sender_id: str,
        target_id: str,
        now: float,
        active_dialogue_uids: Iterable[str] = frozenset(),
        pileon_count: int = 3,
        pileon_pokers: int = 2,
    ) -> str:
        events = self._active_events(session_id, now)
        pokers = {rec.sender_id for rec in events if not rec.is_bot_sender and rec.sender_id}
        if len(events) >= max(1, int(pileon_count)) and len(pokers) >= max(1, int(pileon_pokers)):
            return "group_poke_pileon"
        active_set = {str(uid) for uid in (active_dialogue_uids or ()) if uid}
        sender = str(sender_id or "")
        target = str(target_id or "")
        if (sender and sender in active_set) or (target and target in active_set):
            return "active_dialogue_participant"
        return ""

    def snapshot(
        self,
        session_id: str,
        *,
        sender_id: str,
        target_id: str,
        bot_id: str,
        now: float,
        burst_count: int = 1,
        poke_only: bool = True,
        poke_at_bot: bool = False,
        poke_action_text: str = "",
        poke_target_identity: dict[str, Any] | None = None,
        peer_poke_trigger_reason: str = "",
    ) -> PokeContext:
        events = self._active_events(session_id, now)
        sender = str(sender_id or "")
        target = str(target_id or "")
        bot = str(bot_id or "")
        burst = max(1, int(burst_count or 1))

        if poke_at_bot:
            streak_count = sum(
                1
                for rec in events
                if not rec.is_bot_sender
                and rec.sender_id == sender
                and (rec.is_bot_target or (bot and rec.target_id == bot))
            )
        else:
            streak_count = sum(
                1
                for rec in events
                if not rec.is_bot_sender
                and rec.sender_id == sender
                and (not target or rec.target_id == target)
            )
        sender_streak = max(burst, streak_count)

        ping_pong_turns = 0
        if sender:
            directions: list[str] = []
            for rec in events:
                if rec.is_bot_sender and rec.target_id == sender:
                    direction = "b"
                elif (
                    not rec.is_bot_sender
                    and rec.sender_id == sender
                    and (rec.is_bot_target or (bot and rec.target_id == bot))
                ):
                    direction = "u"
                else:
                    continue
                if not directions or directions[-1] != direction:
                    directions.append(direction)
            ping_pong_turns = max(0, len(directions) - 1)

        group_poke_count = max(burst, len(events))
        pokers = {
            rec.sender_id
            for rec in events
            if not rec.is_bot_sender and rec.sender_id and (not bot or rec.sender_id != bot)
        }
        if sender and (not bot or sender != bot):
            pokers.add(sender)
        distinct_pokers = len(pokers)

        recent_bot_poked_sender = bool(
            sender and any(rec.is_bot_sender and rec.target_id == sender for rec in events)
        )

        return PokeContext(
            poke_only=bool(poke_only),
            poke_at_bot=bool(poke_at_bot),
            burst_count=burst,
            sender_streak=sender_streak,
            ping_pong_turns=ping_pong_turns,
            group_poke_count=group_poke_count,
            distinct_pokers=distinct_pokers,
            poke_action_text=str(poke_action_text or ""),
            poke_target_identity=dict(poke_target_identity) if poke_target_identity is not None else None,
            recent_bot_poked_sender=recent_bot_poked_sender,
            peer_poke_trigger_reason=str(peer_poke_trigger_reason or ""),
        )

    def clear_session(self, session_id: str) -> None:
        self._sessions.pop(str(session_id or ""), None)

    def clear(self) -> None:
        self._sessions.clear()


@dataclass(frozen=True)
class PokeReplyDecision:
    speak: bool
    text: str
    poke_back: bool
    reason: str


class PokeReplyPolicy:
    """Selects a generated social reply or a poke-back."""

    def __init__(self, rng: Optional[random.Random] = None) -> None:
        self._rng = rng if rng is not None else random.Random()

    def decide(
        self,
        *,
        at_bot: bool,
        presence: str = "sensible",
        streak: int = 1,
        vibe: Optional[GroupChatMode] = None,
    ) -> PokeReplyDecision:
        if not at_bot:
            return PokeReplyDecision(False, "", False, "poke_others")

        knob = str(presence or "sensible").strip().lower()
        if knob not in {"ghost", "sensible", "lively"}:
            knob = "sensible"
        count = max(1, int(streak or 1))
        banter = vibe == GroupChatMode.FAST_BANTER

        if count >= 6:
            if self._rng.random() < 0.45:
                return PokeReplyDecision(False, "", False, "poke_spam")
            if self._rng.random() < 0.35:
                return PokeReplyDecision(True, "", True, "poke_annoyed")
            return PokeReplyDecision(True, "", False, "poke_annoyed")
        if count >= 3:
            if self._rng.random() < (0.55 if knob == "lively" else 0.28):
                return PokeReplyDecision(True, "", True, "poke_repeat")
            return PokeReplyDecision(True, "", False, "poke_repeat")

        poke_back_p = {"ghost": 0.12, "sensible": 0.38, "lively": 0.68}.get(knob, 0.38)
        if banter:
            poke_back_p = min(0.9, poke_back_p + 0.12)
        if knob == "lively" and count <= 1 and self._rng.random() < 0.22:
            return PokeReplyDecision(True, "", True, "poke_back_only")

        if self._rng.random() < poke_back_p:
            return PokeReplyDecision(True, "", True, "poke_ack")
        return PokeReplyDecision(True, "", False, "poke_ack")

def next_poke_streak(
    store: dict[tuple[str, str], tuple[int, float]],
    *,
    session_id: str,
    user_id: str,
    now: float,
    window: float = _STREAK_WINDOW,
) -> int:
    """Increment a per-user poke streak; reset after ``window`` idle seconds."""
    key = (str(session_id or ""), str(user_id or ""))
    count, last = store.get(key, (0, 0.0))
    if now - last > window:
        count = 0
    count += 1
    store[key] = (count, now)
    if len(store) > 2000:
        cutoff = now - window
        stale = [item for item, value in store.items() if value[1] < cutoff]
        for item in stale:
            store.pop(item, None)
    return count


def drop_poke_streaks(store: dict[tuple[str, str], tuple[int, float]], session_id: str) -> None:
    sid = str(session_id or "")
    for key in [item for item in store if item[0] == sid]:
        store.pop(key, None)


def consume_self_poke_echo(
    outbound_ledger: Any,
    session_key: str,
    parsed: Any,
    *,
    bot_id: str = "",
    now: float | None = None,
    scope: str = "",
    platform_id: str = "",
) -> bool:
    """Detect and consume a bot-initiated poke echo, backfilling action_text if present."""
    if not getattr(parsed, "has_poke", False):
        return False
    sender_id = str(getattr(parsed, "sender_id", "") or "").strip()
    target_id = str(getattr(parsed, "poke_target_id", "") or "").strip()
    eff_bot_id = str(bot_id or getattr(parsed, "self_id", "") or "").strip()
    action_text = str(getattr(parsed, "poke_action_text", "") or "").strip()
    if outbound_ledger is None:
        return bool(sender_id and eff_bot_id and sender_id == eff_bot_id)
    matcher = getattr(outbound_ledger, "match_and_consume_self_poke_echo", None)
    if not callable(matcher):
        return bool(sender_id and eff_bot_id and sender_id == eff_bot_id)
    return bool(
        matcher(
            session_key,
            sender_id=sender_id,
            target_id=target_id,
            bot_id=eff_bot_id,
            now=now,
            action_text=action_text,
            scope=scope,
            platform_id=platform_id,
        )
    )
